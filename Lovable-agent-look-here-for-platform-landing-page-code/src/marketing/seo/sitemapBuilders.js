/**
 * sitemapBuilders -- Pure helpers that turn CMS document lists into
 * sitemap.xml and llms.txt content. Kept side-effect free (no fs, no
 * fetch, no process.env) so they're trivially unit-testable and shared
 * between the build script (scripts/build-cms-sitemap.mjs) and any
 * future endpoint that wants the same output shape.
 *
 * The orchestrator owns: env reading, CMS fetching, file writes.
 * This module owns: URL composition, XML serialisation, llms.txt
 * appendix formatting, per-section defaults.
 *
 * @module marketing/seo/sitemapBuilders
 */

// Top-level routes the marketing surface always emits. Mirrors the
// hardcoded entries in public/sitemap.xml (the soft-mode fallback).
// Changes here must be reflected in scripts/verify-ssg-output.mjs
// STATIC_ROUTES as well.
export const STATIC_ROUTE_DEFAULTS = Object.freeze([
  { path: "/", changefreq: "weekly", priority: 1.0 },
  { path: "/pricing", changefreq: "weekly", priority: 0.9 },
  { path: "/trust", changefreq: "monthly", priority: 0.7 },
  { path: "/about", changefreq: "monthly", priority: 0.6 },
  { path: "/legal", changefreq: "monthly", priority: 0.5 },
  { path: "/blog", changefreq: "weekly", priority: 0.7 },
  { path: "/changelog", changefreq: "weekly", priority: 0.6 },
  { path: "/docs", changefreq: "weekly", priority: 0.7 },
]);

// Per-section detail-page defaults. Tuned to crawler hints, not hard
// caching contracts. Reassess after a few months of analytics.
export const SECTION_DEFAULTS = Object.freeze({
  legal: { changefreq: "yearly", priority: 0.5 },
  blog: { changefreq: "weekly", priority: 0.6 },
  changelog: { changefreq: "weekly", priority: 0.6 },
  docs: { changefreq: "monthly", priority: 0.7 },
});

// Pretty-printed section labels for the llms.txt appendix. Keys must
// match SECTION_DEFAULTS so a future doc_type addition is a one-line
// change in both maps.
export const SECTION_LABELS = Object.freeze({
  legal: "Legal documents",
  blog: "Blog posts",
  changelog: "Changelog entries",
  docs: "Documentation pages",
});

// XML escape for sitemap <loc>. Sitemap URLs are well-formed by
// construction (no embedded markup) but this stays defensive against
// titles or slugs that ever sneak through unsanitised.
function escapeXml(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

// Trim trailing slashes off a host base so joining with a leading-slash
// path produces a single "/" separator.
function trimTrailingSlash(s) {
  return String(s || "").replace(/\/+$/, "");
}

// Compose an absolute URL from a base and a leading-slash path.
function joinUrl(siteBaseUrl, path) {
  const base = trimTrailingSlash(siteBaseUrl);
  const p = path.startsWith("/") ? path : `/${path}`;
  return `${base}${p}`;
}

// ISO 8601 -> YYYY-MM-DD (sitemap-friendly). Returns null when the
// input is missing or unparseable so callers can skip <lastmod>.
export function formatLastmodDate(iso) {
  if (!iso) return null;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return null;
  return d.toISOString().slice(0, 10);
}

/**
 * Normalise one CMS document row into the minimal shape the sitemap
 * builder needs. Picks canonical_path when present, otherwise falls
 * back to /<docType>/<slug>. Discards anything missing a slug.
 */
export function normalizeDocumentEntry({ docType, doc }) {
  if (!doc || typeof doc !== "object") return null;
  const slug = typeof doc.slug === "string" ? doc.slug.trim() : "";
  if (!slug) return null;
  const path =
    typeof doc.canonical_path === "string" && doc.canonical_path
      ? doc.canonical_path
      : `/${docType}/${slug}`;
  return {
    docType,
    slug,
    path,
    title: typeof doc.title === "string" ? doc.title : "",
    summary: typeof doc.summary === "string" ? doc.summary : "",
    lastmod: formatLastmodDate(
      doc.effective_at || doc.published_at || doc.created_at || null,
    ),
  };
}

/**
 * Build the sitemap.xml body from a static-routes array and a flat
 * list of normalised detail entries. Detail-entry order is preserved
 * as passed in (callers can sort upstream if needed).
 */
export function buildSitemapXml({
  siteBaseUrl,
  staticRoutes = STATIC_ROUTE_DEFAULTS,
  detailEntries = [],
}) {
  const lines = ['<?xml version="1.0" encoding="UTF-8"?>'];
  lines.push(
    "<!-- Generated by scripts/build-cms-sitemap.mjs. Do not edit by hand. -->",
  );
  lines.push('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');
  for (const r of staticRoutes) {
    lines.push("  <url>");
    lines.push(`    <loc>${escapeXml(joinUrl(siteBaseUrl, r.path))}</loc>`);
    lines.push(`    <changefreq>${r.changefreq}</changefreq>`);
    lines.push(`    <priority>${r.priority}</priority>`);
    lines.push("  </url>");
  }
  for (const e of detailEntries) {
    const defaults = SECTION_DEFAULTS[e.docType] || {
      changefreq: "monthly",
      priority: 0.5,
    };
    lines.push("  <url>");
    lines.push(`    <loc>${escapeXml(joinUrl(siteBaseUrl, e.path))}</loc>`);
    if (e.lastmod) {
      lines.push(`    <lastmod>${e.lastmod}</lastmod>`);
    }
    lines.push(`    <changefreq>${defaults.changefreq}</changefreq>`);
    lines.push(`    <priority>${defaults.priority}</priority>`);
    lines.push("  </url>");
  }
  lines.push("</urlset>");
  return lines.join("\n") + "\n";
}

/**
 * Build the llms.txt detail-page appendix. Returns a string starting
 * with a leading newline so callers can concatenate it onto the static
 * template without worrying about separator hygiene. Each section is
 * emitted only when it carries at least one entry.
 *
 * `sections` is a map: docType -> array of normalised entries.
 */
export function buildLlmsTxtAppendix({ siteBaseUrl, sections = {} }) {
  const out = [];
  const orderedTypes = Object.keys(SECTION_LABELS).filter(
    (t) => Array.isArray(sections[t]) && sections[t].length > 0,
  );
  if (orderedTypes.length === 0) return "";
  out.push("");
  out.push(
    "<!-- Detail entries below are generated by " +
      "scripts/build-cms-sitemap.mjs. -->",
  );
  for (const docType of orderedTypes) {
    out.push("");
    out.push(`## ${SECTION_LABELS[docType]}`);
    out.push("");
    for (const e of sections[docType]) {
      const url = joinUrl(siteBaseUrl, e.path);
      const title = (e.title || e.slug).replace(/\s+/g, " ").trim();
      out.push(`- ${url}    ${title}`);
    }
  }
  out.push("");
  return out.join("\n");
}
